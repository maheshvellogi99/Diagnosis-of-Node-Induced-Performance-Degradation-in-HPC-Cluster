# ruff: noqa: E501  (markdown template)
"""Write docs/FROZEN_CONFIG.md for the v1.0-dev-frozen primary (D111). Run only after the D111 freeze
rule passed (scripts/make_phase5c_report.py prints FREEZE).

    uv run python scripts/make_frozen_config.py --run <dev5c run>

Every parameter is copied from the files and dataclasses the runner uses, not retyped: the resolved
Layer 3 policy and variant, and the full text of each config file, with SHA-256 hashes.
"""

from __future__ import annotations

import argparse
import dataclasses
import hashlib
import subprocess

from hpcdiag.layer3 import run_phase5 as RP
from hpcdiag.layer3 import setup as ST
from hpcdiag.layer3 import simulate as SIM
from hpcdiag.utils.run import PROJECT_ROOT, load_config, resolve

FILES = [
    ("configs/phase2_conformal.yaml", "Layer 1: features, model, conformal p-values"),
    ("configs/phase4_layer2.yaml", "Layer 2: Rn(1) e-processes and e-BH"),
    (
        "configs/phase5.yaml",
        "Layer 3: probe model, bets, policy, telemetry (sections probes, evalue, policy, telemetry)",
    ),
    (
        "configs/phase3_inject.yaml",
        "development scenarios (evaluation only, not part of the method)",
    ),
    ("data/raw/CHECKSUMS.txt", "raw data checksums"),
]


def sha(path: str) -> str:
    return hashlib.sha256(resolve(path).read_bytes()).hexdigest()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    a = ap.parse_args()
    cfg = load_config("configs/phase5.yaml")
    run_commit = resolve(f"runs/phase5/{a.run}/git_commit.txt").read_text().strip()
    head = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=PROJECT_ROOT, capture_output=True, text=True
    ).stdout.strip()
    diff = subprocess.run(
        ["git", "diff", "--stat", run_commit, "HEAD", "--", "src", "configs"],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
    ).stdout.strip()
    kw = dict(RP.POLICIES["ig_d109"])
    kw["probe_J"] = float(cfg["evalue"]["probe_J"])
    pol = SIM.Policy("ig_d109", float("nan"), **kw)
    pol_rows = "\n".join(
        f"| {f.name} | {getattr(pol, f.name)} |"
        for f in dataclasses.fields(pol)
        if f.name not in ("name", "B")
    )
    var = ST.VARIANTS["main"]
    var_rows = "\n".join(f"| {f.name} | {getattr(var, f.name)} |" for f in dataclasses.fields(var))
    hashes = "\n".join(f"| `{p}` | {what} | `{sha(p)}` |" for p, what in FILES)
    idx_hash = sha("data/processed/scenarios/index.parquet")
    texts = "\n\n".join(
        f"### `{p}`\n\n```yaml\n{resolve(p).read_text().rstrip()}\n```" for p, _ in FILES[:3]
    )
    out = f"""# Frozen configuration — v1.0-dev-frozen (D111)

The primary configuration, frozen on development seeds by the D111 rule: every D109 validity row passed α + 2 SE
(reports/phase_5c.md §3). Generated by `scripts/make_frozen_config.py` from run {a.run}.

- **Primary:** Layer 1 conformal p-values → Layer 2 Rn(1) e-processes + e-BH (α = 0.1, m = 980) → Layer 3 IG-only
  probing with the D95 exclusion rule, D96 state bets, D98 cross-block telemetry likelihood and the D109 restart
  mixture for probe evidence (J = {pol.probe_J}).
- **Grid code commit:** `{run_commit}` (the commit the evaluation ran at).
- **Commit writing this file:** `{head}`. Changes to `src/` and `configs/` between the two: {"none" if not diff else chr(10) + "```" + chr(10) + diff + chr(10) + "```"}
- **Git tag:** `v1.0-dev-frozen`, on the commit that adds this file.
- **Budget:** B is a deployment choice, not frozen. Gate 5F's headline is B = 7200 node-s/day (D101); the grid is {{0, 300, 1800, 7200}}.

## Hashes (SHA-256)

| File | Role | SHA-256 |
|---|---|---|
{hashes}
| `data/processed/scenarios/index.parquet` | development scenario index | `{idx_hash}` |

## Layer 3 policy as the runner builds it (`run_phase5.POLICIES["ig_d109"]`, J from `evalue.probe_J`)

| Field | Value |
|---|---|
{pol_rows}

Budget rule (PLAN 5.5): B/4 per 6-h block plus carry-over, capped at one day's budget; nodes in rank order of log E;
cleared nodes (π(h0) ≥ 0.95) excluded for `policy.exclude_days`; a node flagged at the current evaluation whose
latest investigation is diagnosed is skipped.

## Layer 3 variant "main" (`setup.VARIANTS["main"]`)

| Field | Value |
|---|---|
{var_rows}

## Every parameter: full text of the method's config files

{texts}

`configs/phase5.yaml` also holds the Phase 5/5b/5c development grids (`grid`, `grid5b`, `grid5c`, `budget_check`) and the
Antarex/Prodigy check settings. They define evaluations, not the method.
"""
    resolve("docs/FROZEN_CONFIG.md").write_text(out)
    print("wrote docs/FROZEN_CONFIG.md")


if __name__ == "__main__":
    main()
