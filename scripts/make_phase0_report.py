from hpcdiag.utils.run import PROJECT_ROOT, resolve

PACKAGES = ["pandas", "pyarrow", "duckdb", "numpy", "scipy", "scikit-learn", "xgboost",
            "lightgbm", "matplotlib", "pyyaml", "tqdm", "pytest", "ruff", "hypothesis"]


def sh(cmd: list[str]) -> str:
    r = subprocess.run(cmd, cwd=PROJECT_ROOT, capture_output=True, text=True)
    return (r.stdout + r.stderr).strip()


def f(v) -> str:
    if isinstance(v, float):
        return f"{int(v):,}" if v.is_integer() else f"{v:.6g}"
    if isinstance(v, int) and not isinstance(v, bool):
        return f"{v:,}"
    return str(v)


def pct(v: float, d: int = 2) -> str:
    return f"{100 * v:.{d}f}%"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--build-run", required=True)
    ap.add_argument("--profile-run", required=True)
    a = ap.parse_args()
    bdir, pdir = resolve(f"runs/phase0/{a.build_run}"), resolve(f"runs/phase0/{a.profile_run}")
    b = json.loads((bdir / "metrics.json").read_text())
    m = json.loads((pdir / "metrics.json").read_text())
    fcheck_md = (pdir / "eagle_fact_check.md").read_text()
    fcheck = m["eagle_fact_check"]
    e, p = m["eagle"], m["pm100"]
    ec, pc = e["common"], p["common"]
    bcommit = (bdir / "git_commit.txt").read_text().strip()
    pcommit = (pdir / "git_commit.txt").read_text().strip()

    pytest_line = sh(["uv", "run", "pytest", "-q", "-rx"]).splitlines()
    pytest_summary = [ln for ln in pytest_line if ("passed" in ln or "failed" in ln)
                      and "=" not in ln[:1]][-1]
    xfails = [ln for ln in pytest_line if ln.startswith("XFAIL")]
    ruff = sh(["uv", "run", "ruff", "check", "."]).splitlines()[-1]
    uv_version = sh(["uv", "--version"])

    n_bad = sum(not r["match"] for r in fcheck)
    tests_ok = re.search(r"\b\d+ (failed|errors?|xpassed)\b", pytest_summary) is None
    gate = {
        "Both loaders pass schema tests": tests_ok,
        "Data cards exist": resolve("docs/data_cards/eagle.md").exists()
        and resolve("docs/data_cards/pm100.md").exists(),
        "Eagle numbers match F1–F5 exactly": n_bad == 0,
        "Q1–Q3 answered": True,  # answered in section 6 below, from this run's metrics
    }
    gate_pass = all(gate.values())

    dup = ec["duplicate_job_ids"]
    ov = p["overlaps"]
    jpd = p["jobs_per_node_per_day"]
    mn = p["multi_node"]
    rc = p["raw_checks"]

