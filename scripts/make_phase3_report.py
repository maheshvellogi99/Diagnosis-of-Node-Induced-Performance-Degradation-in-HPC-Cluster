# ruff: noqa: E501  (markdown report template: table rows are long by nature)
"""Render reports/phase_3.md from the Phase 3 generation run (PLAN.md §7.6).

    uv run python scripts/make_phase3_report.py --run <phase3 run id>
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys

import numpy as np
import pandas as pd

from hpcdiag.utils.run import PROJECT_ROOT, resolve


def sh(cmd: list[str]) -> str:
    r = subprocess.run(cmd, cwd=PROJECT_ROOT, capture_output=True, text=True)
    return (r.stdout + r.stderr).strip()


def f(v, d=0) -> str:
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "—"
    if isinstance(v, (int, np.integer)):
        return f"{int(v):,}"
    return f"{v:,.{d}f}"


def mmm(x: pd.Series) -> str:
    return f"{f(int(x.median()) if float(x.median()).is_integer() else float(x.median()), 1)} ({f(int(x.min()))}–{f(int(x.max()))})"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    a = ap.parse_args()
    rdir = resolve(f"runs/phase3/{a.run}")
    m = json.loads((rdir / "metrics.json").read_text())
    # keep_default_na=False: the kind "null" must not be parsed as a missing value
    idx = pd.read_csv(rdir / "scenario_counts.csv", keep_default_na=False, na_values=[""])
    idx["base_type"] = np.where(idx["base"] == "real", "real", "random")
    commit = (rdir / "git_commit.txt").read_text().strip()
    shutil.copy(rdir / "scenario_counts.csv", resolve("reports/phase3_scenario_counts.csv"))

    pytest_lines = sh(["uv", "run", "pytest", "-q", "tests/test_inject.py"]).splitlines()
    t_inject = [ln for ln in pytest_lines if re.search(r"\d+ passed", ln)][-1]
    all_lines = sh(["uv", "run", "pytest", "-q"]).splitlines()
    t_all = [ln for ln in all_lines if re.search(r"\d+ passed", ln)][-1]
    ruff = sh(["uv", "run", "ruff", "check", "."]).splitlines()[-1]
    size = sh(["du", "-sh", str(resolve("data/processed/scenarios"))]).split()[0]
    unit_ok = "failed" not in t_inject and "error" not in t_inject
    gate = unit_ok and m["n_scenarios"] == len(idx)

    s = "# Phase 3 report — Semi-synthetic ground truth on PM100\n\n"
    s += f"_Generated by `scripts/make_phase3_report.py` from run `{a.run}` (commit `{commit[:12]}`). Do not edit by hand._\n\n"
    s += f"""## 1. Result

**Gate 3: {"PASS" if gate else "FAIL"}**

| criterion (PLAN Gate 3) | evidence | result |
|---|---|---|
| unaffected jobs are byte-identical | unit test on a hand-built trace; and for every one of the {f(m['n_scenarios'])} generated scenarios the materialized table's unaffected rows were compared with the base (`DataFrame.equals`) — the generator aborts on any difference | {"pass" if gate else "**FAIL**"} |
| affected jobs follow the formula | hand-computed unit tests for node (s·T), node_partial (T(1+(s−1)φ), φ = 0.5 case), user_decoy, system_shock, censoring | {"pass" if unit_ok else "**FAIL**"} |
| truth tables match the injected set exactly | for every generated scenario the affected rows and multipliers were re-derived from the truth table alone by an independent per-row implementation (`inject.verify`) and compared with the stored changes — the generator aborts on any mismatch | {"pass" if gate else "**FAIL**"} |
| contract still valid after injection | `validate_jobs` on every materialized scenario (censored ⇔ state TIMEOUT, no negative run time, row_id unique) | {"pass" if gate else "**FAIL**"} |
| same seed → same output | unit tests (random placement, degraded-node draws) | {"pass" if unit_ok else "**FAIL**"} |

Tests: inject `{t_inject}`; all `{t_all}`; lint `{ruff}`.

## 2. Setup (D29–D35)

- Mode E freeze time (Phase 2 PM100, L = 45): **{m['freeze_time']}**; onset window (D31, D34) **[{m['onset_window'][0]}, {m['onset_window'][1]}]** = [freeze + 7 d, trace end − 14 d]; trace end (max end_time of COMPLETED/TIMEOUT rows) {m['trace_end']}.
- Submission gaps excluded (data card, profile run): """ + "; ".join(f"{a_} → {b_}" for a_, b_ in m["gaps"]) + f""". Draws inside a gap are redrawn; redraws are counted per scenario (§5).
- Only COMPLETED/TIMEOUT rows can be affected; other rows are copied unchanged. The main-population filter (run_time > 30 s) is NOT applied here; Phase 4 re-filters after injection (D34). Base main-population size {f(m['base_main_population_size'])} jobs.
- Censoring (D34): if s·T (or the partial multiplier × T) exceeds walltime_req_s, then T' = max(T, limit), censored = TRUE, state = TIMEOUT (state_raw kept as in the source). Start times are fixed; end' = start + T'.
- Bases: real placement + 20 random-placement bases (D29); scenario seed k on a random base uses base k (D35), so every random-base scenario has a null on the same placement.
- Pairing: the scenario generator's key excludes s and node vs node_partial, so for a given base, K and seed all four s values and both node kinds use the same degraded nodes, onsets and causes; user_decoy and system_shock draws are shared across s the same way.
- Causes (D30): balanced mix of cpu / cache / mbw per scenario (counts differ by at most 1), seeded.
- Storage: only affected rows are stored (`changes.parquet`) with `truth.parquet` and `scenario.json` per scenario; random-placement node tables once per base in `data/processed/scenarios/_bases/`. Total size on disk: {size}. Load with `hpcdiag.inject.store.load_scenario`.

## 3. Scenario grid (answer 8)

| kind | real base | random bases | total |
|---|---|---|---|
"""
    g = idx.groupby(["kind", "base_type"]).size().unstack(fill_value=0)
    for k in ["node", "node_partial", "user_decoy", "system_shock", "null"]:
        if k in g.index:
            r, rd = int(g.loc[k].get("real", 0)), int(g.loc[k].get("random", 0))
            s += f"| {k} | {r} | {rd} | {r + rd} |\n"
    s += f"| **all** | {int((idx['base_type'] == 'real').sum())} | {int((idx['base_type'] == 'random').sum())} | **{len(idx)}** |\n\n"
    s += ("node / node_partial: K ∈ {1, 2, 5}% × s ∈ {1.1, 1.2, 1.3, 1.5} × 20 seeds per base type; user_decoy / system_shock: "
          "s × 20 seeds per base type; null: one per base (20 random + real).\n\n")

    # ---- per family summaries
    s += "## 4. Counts per scenario family (median (min–max) over the 20 seeds)\n\n"
    s += ("Columns: affected = jobs whose run time was changed; main after = affected jobs with run time > 30 s after injection; "
          "cross 30 s = affected jobs with T ≤ 30 s before and T' > 30 s after; censored = newly censored by injection; "
          "nodes touched = distinct nodes (in that base's placement) running at least one affected job; degraded with effect = "
          "degraded nodes that run at least one affected job.\n\n")
    s += "| kind | base | K% (K) | s | affected | main after | cross 30 s | censored | nodes touched | degraded with effect |\n|---|---|---|---|---|---|---|---|---|---|\n"
    nk = idx[idx["kind"].isin(["node", "node_partial"])]
    for (kind, bt, kp, sv), g2 in nk.groupby(["kind", "base_type", "K_pct", "s"]):
        Ks = sorted(g2["K"].dropna().astype(int).unique())
        s += (f"| {kind} | {bt} | {int(kp)} ({'/'.join(map(str, Ks))}) | {sv} | {mmm(g2['n_affected'])} | {mmm(g2['n_affected_main_after'])} | "
              f"{mmm(g2['n_cross_30s'])} | {mmm(g2['n_censored_by_injection'])} | {mmm(g2['n_nodes_touched'])} | {mmm(g2['n_degraded_nodes_with_affected_jobs'])} |\n")
    s += "\n| kind | base | s | affected | main after | cross 30 s | censored | nodes touched |\n|---|---|---|---|---|---|---|---|\n"
    ok = idx[idx["kind"].isin(["user_decoy", "system_shock"])]
    for (kind, bt, sv), g2 in ok.groupby(["kind", "base_type", "s"]):
        s += (f"| {kind} | {bt} | {sv} | {mmm(g2['n_affected'])} | {mmm(g2['n_affected_main_after'])} | {mmm(g2['n_cross_30s'])} | "
              f"{mmm(g2['n_censored_by_injection'])} | {mmm(g2['n_nodes_touched'])} |\n")
    nl = idx[idx["kind"] == "null"]
    s += f"\nnull scenarios: {len(nl)} ({int((nl['base'] == 'real').sum())} real + {int((nl['base'] != 'real').sum())} random); affected jobs in all of them: {int(nl['n_affected'].sum())}.\n\n"
    z = idx[(idx["kind"] != "null") & (idx["n_affected"] == 0)]
    s += f"**Degenerate scenarios (no affected job): {len(z)}**"
    if len(z):
        zz = z.groupby(["kind", "base_type"]).size()
        s += " — " + "; ".join(f"{k} / {b}: {n}" for (k, b), n in zz.items())
        s += (". They come from onset or shock draws where no eligible job matches (e.g. a 6-h shock window in which no "
              "COMPLETED/TIMEOUT job ended). The rules (D31, D34) do not require a redraw, so they are kept and listed; "
              "Phase 4 should treat them as null-like and report them separately. IDs: " + ", ".join(f"`{x}`" for x in z["scenario_id"].head(12))
              + (" …" if len(z) > 12 else "") + ".")
    s += "\n\n"

    # ---- draws
    s += "## 5. Draws and redraws\n\n"
    on = nk.drop_duplicates(["base", "K_pct", "seed"])
    s += f"- Degraded-node draws (one per base × K × seed): {len(on)}; onset redraws because of a gap: total {int(on['onset_redraws'].sum())}, max per draw {int(on['onset_redraws'].max())}.\n"
    dc = idx[idx["kind"] == "user_decoy"].drop_duplicates(["base", "seed"])
    s += f"- Decoy draws (one per base × seed): {len(dc)}; distinct users {dc['user'].nunique()}; t0 redraws (gap or no qualifying user, D34): total {int(dc['t0_redraws'].sum())}, max {int(dc['t0_redraws'].max())}.\n"
    sk = idx[idx["kind"] == "system_shock"].drop_duplicates(["base", "seed"])
    s += f"- Shock draws: {len(sk)}; t1 redraws total {int(sk['t1_redraws'].sum())}.\n\n"

    # ---- per-node counts
    s += "## 6. Per-node COMPLETED/TIMEOUT job counts: real vs random placement (A5)\n\n| base | nodes | min | p10 | median | p90 | max |\n|---|---|---|---|---|---|---|\n"
    pn = m["per_node_eligible_job_counts"]
    for b in ["real"] + sorted(k for k in pn if k != "real")[:3]:
        x = pn[b]
        s += f"| {b} | {f(x['nodes'])} | {f(x['min'])} | {f(x['p10'], 1)} | {f(x['median'], 1)} | {f(x['p90'], 1)} | {f(x['max'])} |\n"
    rnd = pd.DataFrame({k: v for k, v in pn.items() if k != "real"}).T
    s += (f"| random bases (all 20): median of medians | — | — | — | {f(float(rnd['median'].median()), 1)} | — | — |\n"
          f"| random bases (all 20): range of max | — | — | — | — | — | {f(int(rnd['max'].min()))}–{f(int(rnd['max'].max()))} |\n\n"
          "Full per-base values are in the run's metrics.json (`per_node_eligible_job_counts`).\n\n")

    s += """## 7. Limitations (stated, not fixed)

- Start times are fixed and there is no queue model: a slowed job can overlap the next job on the same node.
- Random placement ignores node occupancy: two jobs can run on the same node at the same time in a random base.
- System shock selects jobs by their ORIGINAL end_time; after scaling, their end_time moves out of the window.
- Straggler model [A]: a multi-node job on several degraded nodes is slowed once (s·T), never compounded.

"""
    s += f"""## 8. Commands and outputs

```bash
uv run python -m hpcdiag.inject.run_inject --config configs/phase3_inject.yaml   # run {a.run}
uv run pytest -q
uv run python scripts/make_phase3_report.py --run {a.run}
```

- Scenarios: `data/processed/scenarios/<scenario_id>/` (git-ignored), index `data/processed/scenarios/index.parquet`.
- Full per-scenario table (versioned): `reports/phase3_scenario_counts.csv`.
- Generation time: {m['seconds'] / 60:.1f} min. Two smoke runs on a tiny grid (output in the session scratchpad, not used here) are in the run registry; the first failed on a path bug that was fixed.

Phase 3 complete. Stopped; Phase 4 not started.
"""
    resolve("reports/phase_3.md").write_text(s)
    print("wrote reports/phase_3.md; Gate 3", "PASS" if gate else "FAIL")
    return 0


if __name__ == "__main__":
    sys.exit(main())
